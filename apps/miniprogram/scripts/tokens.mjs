// Turns opendesigner/build/css/tokens.css into what the Mini Program can read:
// - src/styles/tokens.css: the light theme, scoped to `.ds` (WeChat's WXSS rejects :root and attribute selectors).
// - src/theme.ts: the few hex values app.config and the canvas need (neither can read CSS variables).
// Run `pnpm --filter miniprogram tokens` after `engine.py build`.
import { readFileSync, writeFileSync } from 'node:fs'

const src = readFileSync(new URL('../../../opendesigner/build/css/tokens.css', import.meta.url), 'utf8')

/** Declarations of the block that opens on the line matching `head` (and closes at its own indentation). */
function block(head) {
  const lines = src.split('\n')
  const start = lines.findIndex((l) => l.trim() === head)
  if (start < 0) throw new Error(`No block "${head}" in tokens.css`)
  const indent = lines[start].match(/^\s*/)[0]
  const end = lines.findIndex((l, i) => i > start && l === `${indent}}`)
  return lines.slice(start + 1, end).filter((l) => l.trim().startsWith('--ds-'))
}

const base = [':root {', ':root, [data-theme="light"] {', ':root, [data-density="spacious"] {', ':root, [data-motion="standard"] {'].flatMap(block)
const reduced = block(':root:not([data-motion="standard"]) {')

const out = `/* Generated by scripts/tokens.mjs from opendesigner/build/css/tokens.css. Do not edit. */
.ds {
${base.join('\n')}
}
@media (prefers-reduced-motion: reduce) {
  .ds {
${reduced.join('\n')}
  }
}
`
writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), out)

// Resolve var() chains to plain values for the config.
const values = Object.fromEntries(base.map((l) => l.trim().replace(/;$/, '').split(/:\s(.+)/).slice(0, 2)))
const resolve = (name) => {
  let v = values[name]
  for (let i = 0; i < 10 && v?.startsWith('var('); i++) v = values[v.slice(4, -1)]
  return v
}
const theme = {
  navBackground: resolve('--ds-color-surface-nav'),
  text: resolve('--ds-color-text-primary'),
  textSecondary: resolve('--ds-color-text-secondary'),
  accent: resolve('--ds-color-text-accent'),
  border: resolve('--ds-color-border-separator'),
  // The invitation card is drawn on a canvas, which cannot read CSS variables either.
  brand: resolve('--ds-color-accent-light-9'),
  ink: resolve('--ds-color-neutral-light-12'),
  paper: resolve('--ds-color-neutral-light-1'),
  muted: resolve('--ds-color-neutral-light-11'),
  slit: resolve('--ds-color-neutral-light-6'),
}
writeFileSync(
  new URL('../src/theme.ts', import.meta.url),
  `// Generated by scripts/tokens.mjs from the design tokens. Do not edit.\nexport const theme = ${JSON.stringify(theme, null, 2)} as const\n`,
)
console.log(`tokens.css: ${base.length} tokens; theme.ts:`, theme)
